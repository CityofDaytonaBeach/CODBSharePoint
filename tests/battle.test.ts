function peopleInsightsSource(): string {
  return `import * as React from 'react';
import styles from './PeopleInsights.module.scss';

export default class PeopleInsights extends React.Component<any, any> {
  public state = { people: [{ displayName: 'Ada Lovelace', department: 'IT' }, { displayName: 'Grace Hopper', department: 'Finance' }] };

  public async componentDidMount(): Promise<void> {
    const factory = this.props.context?.msGraphClientFactory;
    if (!factory) return;
    const client = await factory.getClient('3');
    await client.api('/users').version('v1.0').select('displayName,department,mail').top(5).get();
    await client.api('/groups').version('v1.0').select('displayName,mail').top(5).get();
    await client.api('/sites/root').version('v1.0').get();
  }

  public render(): React.ReactElement<any> {
    return <section className={styles.panel}>
      <h2>People Insights</h2>
      <div className={styles.people}>{this.state.people.map((person: any) => <div className={styles.person} key={person.displayName}>
        <span>{person.displayName}</span><small>{person.department}</small>
      </div>)}</div>
    </section>;
  }
}
`;
}

